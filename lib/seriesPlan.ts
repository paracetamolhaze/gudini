export type SeriesPosition = { number: number; total: number; next?: string };

const key = (s: string) => s.toLowerCase().replace(/ё/g, "е").replace(/\(18\+\)/g, "").replace(/[^\p{L}\p{N}]+/gu, " ").trim();
const head = (s: string) => key(s.split(":")[0]);

/** Место темы в плане: точное совпадение, иначе единственное совпадение начала до двоеточия («Биткоин за минуту»). */
export function seriesPosition(topic: string): SeriesPosition | null {
  const k = key(topic);
  let i = CRYPTO_SERIES.findIndex((t) => key(t) === k);
  if (i < 0) {
    const h = head(topic);
    const hits = CRYPTO_SERIES.flatMap((t, j) => (h.length >= 8 && head(t) === h ? [j] : []));
    if (hits.length === 1) i = hits[0];
  }
  return i < 0 ? null : { number: i + 1, total: CRYPTO_SERIES.length, next: CRYPTO_SERIES[i + 1] };
}

/** Строка для сценариста: какой это ролик серии и что обещать в призыве. Пусто, если темы нет в плане. */
export function seriesLine(topic: string): string {
  const p = seriesPosition(topic);
  if (!p) return "";
  return p.next
    ? `Это ролик ${p.number} из ${p.total} в серии для новичков про крипту. Следующий ролик серии: «${p.next}». В призыве пообещай зрителю именно его, своими словами.`
    : `Это последний, ${p.number}-й ролик серии для новичков про крипту. В призыве поблагодари, что зритель дошёл до конца серии, и задай ему вопрос.`;
}
